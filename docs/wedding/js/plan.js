function flattenTasks(phasesList) {
  const list = []
  phasesList.forEach((phase) => {
    phase.months.forEach((month) => {
      month.groups.forEach((group, gi) => {
        group.tasks.forEach((text, ti) => {
          const id = `${month.id}-${gi}-${ti}`
          list.push({
            id,
            text,
            phaseId: phase.id,
            monthId: month.id,
            monthLabel: month.label,
            groupTitle: group.title
          })
        })
      })
    })
  })
  return list
}

